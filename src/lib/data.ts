export function getState(slug: string): StateInfo | undefined {
  return STATES.find((s) => s.slug === slug);
}

export function getCitiesForState(stateSlug: string): CityInfo[] {
  return CITIES.filter((c) => c.stateSlug === stateSlug);
}

export function getCompaniesForState(stateSlug: string): Company[] {
  return COMPANIES.filter((c) => c.stateSlug === stateSlug);
}

export function getCompany(stateSlug: string, companySlug: string): Company | undefined {
  return COMPANIES.find((c) => c.stateSlug === stateSlug && c.slug === companySlug);
}

export function getCompanyCountForState(stateSlug: string): number {
  return COMPANIES.filter((c) => c.stateSlug === stateSlug).length;
}

export function searchCompanies(query: string): Company[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return COMPANIES.filter((c) => {
    const city = CITIES.find((ci) => ci.slug === c.citySlug)?.name ?? "";
    const state = getState(c.stateSlug)?.name ?? "";
    return (
      c.name.toLowerCase().includes(q) ||
      c.type.toLowerCase().includes(q) ||
      city.toLowerCase().includes(q) ||
      state.toLowerCase().includes(q) ||
      c.specializations.some((s) => s.toLowerCase().includes(q))
    );
  });
}

// Bidcore / BidcoreAI only has two workspaces: India has its own database;
// everyone else (US included) shares the main one. "market" is this bucket,
// not the person's actual country — which is why it stays IN / US / OTHER
// even though the Country field itself now lists every country.
export type Market = "IN" | "US" | "OTHER";
export const marketForCountry = (code: string): Market => (code === "IN" ? "IN" : code === "US" ? "US" : "OTHER");
export const isMarket = (v: string): v is Market => v === "IN" || v === "US" || v === "OTHER";
